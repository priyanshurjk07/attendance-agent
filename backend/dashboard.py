import json
import os
import subprocess
import sys

import pandas as pd
import streamlit as st

st.set_page_config(page_title="Attendance & Engagement Agent", layout="wide")
st.title("Multimodal Attendance & Engagement Agent")

REPORT = "session_report.json"

if st.button("Record new session (15 seconds)"):
    with st.spinner("Recording... look at the camera window that opens"):
        subprocess.run([sys.executable, "run_pipeline.py", "15"])
    st.rerun()

if not os.path.exists(REPORT):
    st.warning("No session report yet. Click the button above to record one.")
    st.stop()

with open(REPORT) as f:
    report = json.load(f)

engagement = report["engagement"]
analytics = report["analytics"]
part = analytics["participation"]

# Top numbers
c1, c2, c3, c4 = st.columns(4)
c1.metric("Attendance", "Present" if analytics["attendance"]["marked_present"] else "Not marked")
c2.metric("Average engagement", f"{engagement['average_score']} ({engagement['overall_level']})")
c3.metric("Visible time", f"{part['visible_seconds']} s")
c4.metric("Speaking time", f"{part['speaking_seconds']} s")

# Engagement timeline
st.subheader("Engagement timeline")
df = pd.DataFrame(engagement["segments"])
df["segment"] = df["start"].astype(str) + "-" + df["end"].astype(str) + "s"
st.bar_chart(df.set_index("segment")["score"])
st.caption("Score (0-100) for each 2-second segment of the session.")

with st.expander("Segment details"):
    st.dataframe(df[["start", "end", "score", "level",
                     "face_present_ratio", "speech_ratio", "silence_ratio"]],
                 width="stretch")

left, right = st.columns(2)

# Teaching suggestions
with left:
    st.subheader("Teaching suggestions")
    for r in report["recommendations"]:
        text = f"**{r['time']}**: {r['message']}"
        if r["type"] == "alert":
            st.error(text)
        elif r["type"] == "warning":
            st.warning(text)
        else:
            st.success(text)

# AI insight
with right:
    st.subheader("AI insight")
    ai = report["ai_insight"]
    st.info(f"**Insight:** {ai['insight']}\n\n**Recommendation:** {ai['recommendation']}")
    st.caption("Generated by AI" if ai["source"] == "ai" else "Generated by rules (AI unavailable)")

# Participant reflection
st.subheader("Session reflection")
for note in analytics["reflection"]:
    st.write("- " + note)
st.caption(analytics["privacy_note"])